// TestEngineSetFileState_StoreAndRetrieve verifies all public constants.
func TestEngineSetFileState_StoreAndRetrieve(t *testing.T) {
	engine, _ := newTestEngine(t, newMockBackend(), t.TempDir())
	const p = "/local/file.txt"

	cases := []types.FileState{
		types.FileStateLocal,
		types.FileStatePending,
		types.FileStateUploading,
		types.FileStateSynced,
		types.FileStateConflict,
		types.FileStateError,
		types.FileStateExcluded,
	}
	for _, state := range cases {
		engine.SetFileState(p, state)
		got := engine.GetFileState(p)
		assert.Equal(t, state, got, "expected state %q, got %q", state, got)
	}
}

